// Generates R/rates.R from the Go package (rates.go, baremekm.go),
// the single source of the rates. Never edit R/rates.R by hand.
//
// Usage: node tools/gen_data.mjs [path/to/macalc-go/baremekm]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const DEFAULT_GO = resolve(ROOT, "../macalc-go/baremekm");
export const DEST = resolve(ROOT, "R/rates.R");

// Reads the Go package. Numbers keep their text (`text`) and their value.
export function parse(goDir = DEFAULT_GO) {
  const api = readFileSync(resolve(goDir, "baremekm.go"), "utf-8");
  const src = readFileSync(resolve(goDir, "rates.go"), "utf-8");
  const classes = [...api.matchAll(/^\s*(\w+)\s+Class = "(\w+)"/gm)].map((m) => ({ go: m[1], value: m[2] }));
  const vehicles = Object.fromEntries([...api.matchAll(/case (Car|Motorcycle|Moped):\s*return "(\w+)"/g)].map((m) => [m[1], m[2]]));
  const sources = [...api.matchAll(/case (\d{4}):\s*return "([^"\\]*)", nil/g)].map((m) => ({ year: Number(m[1]), text: m[2] }));
  const row = /^\s*\{(\d{4}), (Car|Motorcycle|Moped), (\w+), (\d+), (\d+|math\.Inf\(1\)), ([\d.]+), (\d+)\},\s*$/;
  const body = src.split(/\r?\n/).filter((l) => /^\s*\{\d/.test(l));
  const rates = body.map((l) => {
    const m = l.match(row);
    if (!m) throw new Error(`unparsed rate line: ${l.trim()}`);
    const cls = classes.find((c) => c.go === m[3]);
    if (!cls) throw new Error(`unknown class ${m[3]}`);
    return {
      year: Number(m[1]), vehicle: m[2], vehicleName: vehicles[m[2]], cls: m[3], classValue: cls.value,
      minKm: Number(m[4]), maxKm: m[5].startsWith("math.Inf") ? Infinity : Number(m[5]), maxText: m[5],
      coef: Number(m[6]), coefText: m[6], constant: Number(m[7]),
    };
  });
  if (classes.length !== 9) throw new Error(`classes = ${classes.length}, want 9`);
  if (Object.keys(vehicles).length !== 3) throw new Error(`vehicles = ${Object.keys(vehicles).length}, want 3`);
  if (sources.length !== 5) throw new Error(`sources = ${sources.length}, want 5`);
  if (rates.length !== 135) throw new Error(`rates = ${rates.length}, want 135`);
  return { classes, vehicles, sources, rates };
}

// Canonical row used by the cross-check: [year, vehicle name, class value, minKm, maxKm, coef, constant].
export const canon = (r) => [r.year, r.vehicleName, r.classValue, r.minKm, r.maxKm, r.coef, r.constant];

// R string in ASCII (the Go sources are ASCII; anything else is refused).
function r(s) {
  if (!/^[\x20-\x7e]*$/.test(s)) throw new Error(`non ASCII character in ${JSON.stringify(s)}`);
  return JSON.stringify(s);
}

function generate(goDir) {
  const { sources, rates } = parse(goDir);
  const col = (name, f) => `  ${name} = c(${rates.map(f).join(", ")}),`;
  const out = [
    "# GENERATED by tools/gen_data.mjs from macalc-go/baremekm (rates.go, baremekm.go). Do not edit.",
    "",
    "# The 135 rates, in the order of the source.",
    "rates_table <- data.frame(",
    col("year", (x) => `${x.year}L`),
    col("vehicle", (x) => r(x.vehicleName)),
    col("class", (x) => r(x.classValue)),
    col("min_km", (x) => `${x.minKm}`),
    col("max_km", (x) => (x.maxKm === Infinity ? "Inf" : x.maxText)),
    col("coef", (x) => x.coefText),
    col("constant", (x) => `${x.constant}`),
    "  stringsAsFactors = FALSE",
    ")",
    "",
    "# Official text against which each declaration year was cross-checked.",
    "source_texts <- c(",
    sources.map((s) => `  "${s.year}" = ${r(s.text)}`).join(",\n"),
    ")",
    "",
  ];
  writeFileSync(DEST, out.join("\n"), { encoding: "utf-8" });
  console.log(`${rates.length} rates, ${sources.length} sources -> ${DEST}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) generate(process.argv[2] || DEFAULT_GO);
